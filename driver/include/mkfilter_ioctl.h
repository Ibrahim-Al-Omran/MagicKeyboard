#ifndef MKFILTER_IOCTL_H
#define MKFILTER_IOCTL_H

#include <devioctl.h>

#include "mkfilter_protocol.h"

/*
 * 0x8337 is in Microsoft's vendor-defined device-type range. These IOCTLs are
 * METHOD_BUFFERED so validation never follows caller-controlled pointers.
 */
#define MKFILTER_IOCTL_DEVICE_TYPE 0x8337u

#define IOCTL_MKFILTER_QUERY_CAPABILITIES \
    CTL_CODE(MKFILTER_IOCTL_DEVICE_TYPE, 0x800u, METHOD_BUFFERED, FILE_READ_ACCESS)

#define IOCTL_MKFILTER_GET_MAPPING \
    CTL_CODE(MKFILTER_IOCTL_DEVICE_TYPE, 0x801u, METHOD_BUFFERED, FILE_READ_ACCESS)

#define IOCTL_MKFILTER_SET_MAPPING \
    CTL_CODE(MKFILTER_IOCTL_DEVICE_TYPE, 0x802u, METHOD_BUFFERED, FILE_WRITE_ACCESS)

#define IOCTL_MKFILTER_CLEAR_MAPPING \
    CTL_CODE(MKFILTER_IOCTL_DEVICE_TYPE, 0x803u, METHOD_BUFFERED, FILE_WRITE_ACCESS)

#endif
